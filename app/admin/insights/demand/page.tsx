'use client'

import { useState } from 'react'
import { RefreshCw, Sparkles } from 'lucide-react'
import clsx from 'clsx'
import DemandRadarPanel from '@/components/analytics/DemandRadarPanel'
import OpportunityByRegionPanel from '@/components/analytics/OpportunityByRegionPanel'
import FilterBar from '@/components/analytics/FilterBar'
import ClinicIntentPanel from '@/components/analytics/ClinicIntentPanel'
import RevenuePotentialPanel from '@/components/analytics/RevenuePotentialPanel'
import type { DateRangeOption, ServiceLineFilter } from '@/hooks/useRegionDemandAnalytics'
import StatusBadge from '@/components/StatusBadge'
import Link from 'next/link'

export default function DemandInsightsPage() {
  const [serviceLine, setServiceLine] = useState<ServiceLineFilter>('ALL')
  const [dateRange, setDateRange] = useState<DateRangeOption>('30d')
  const [refreshing, setRefreshing] = useState(false)

  const handleRefreshForecasts = async () => {
    setRefreshing(true)
    // Trigger predictive demand modeling via scheduler
    try {
      const response = await fetch('/api/admin/dealflow/scheduler', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'trigger',
          scheduleType: 'daily', // Full cycle includes predictive modeling
        }),
      })
      if (response.ok) {
        // Reload page to show updated forecasts
        window.location.reload()
      }
    } catch (error) {
      console.error('Error refreshing forecasts:', error)
    } finally {
      setRefreshing(false)
    }
  }

  return (
    <div className="p-8 bg-dark-bg min-h-screen space-y-6">
      <div className="flex items-start justify-between gap-4">
        <div>
          <h1 className="text-3xl font-bold text-white">Demand &amp; Opportunities</h1>
          <p className="text-gray-400 mt-2">
            Real-time insight into regional TRT, Weight Loss, and IV Therapy demand across the U.S.
          </p>
          <div className="mt-3 flex items-center gap-3">
            <span className="px-2 py-1 bg-primary/10 text-primary text-xs rounded border border-primary/30">
              Forecasts generated by Novalyte Predictive Engine (Assessments + Revenue + Region Signals)
            </span>
            <button
              onClick={handleRefreshForecasts}
              disabled={refreshing}
              className="px-3 py-1 bg-dark-surface border border-dark-border text-gray-300 rounded text-xs hover:bg-dark-hover transition-colors disabled:opacity-50 flex items-center gap-2"
            >
              <RefreshCw className={clsx('w-3 h-3', refreshing && 'animate-spin')} />
              Refresh Forecasts
            </button>
            <Link
              href="/admin/dealflow-drops"
              className="px-3 py-1 bg-dark-surface border border-dark-border text-gray-300 rounded text-xs hover:bg-dark-hover transition-colors flex items-center gap-2"
            >
              <Sparkles className="w-3 h-3" />
              View Daily Drop
            </Link>
          </div>
        </div>
        <StatusBadge status="live" />
      </div>

      <FilterBar
        serviceLine={serviceLine}
        dateRange={dateRange}
        onServiceLineChange={setServiceLine}
        onDateRangeChange={setDateRange}
      />

      <div className="space-y-6">
        <DemandRadarPanel serviceLine={serviceLine} dateRange={dateRange} />
        <OpportunityByRegionPanel serviceLine={serviceLine} dateRange={dateRange} />
        <ClinicIntentPanel serviceLine={serviceLine} dateRange={dateRange} />
        <RevenuePotentialPanel serviceLine={serviceLine} dateRange={dateRange} />
      </div>
    </div>
  )
}
